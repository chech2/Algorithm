SELECT CATEGORY, PRICE AS MAX_PRICE, PRODUCT_NAME
FROM FOOD_PRODUCT AS FP
JOIN (
    SELECT PRODUCT_ID AS ID, ROW_NUMBER() OVER (PARTITION BY CATEGORY ORDER BY PRICE DESC) AS R
    FROM FOOD_PRODUCT
) RANK_TABLE
ON FP.PRODUCT_ID = RANK_TABLE.ID
WHERE CATEGORY IN ('과자', '국', '김치', '식용유')
AND R = 1
ORDER BY MAX_PRICE DESC

