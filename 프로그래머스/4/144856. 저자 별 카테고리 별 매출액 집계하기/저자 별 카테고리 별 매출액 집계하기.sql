SELECT B.AUTHOR_ID, AUTHOR_NAME, CATEGORY, SUM(TOTAL_SALES * PRICE) AS TOTAL_PRICE
FROM BOOK B
JOIN (
    SELECT BOOK_ID, SUM(SALES) AS TOTAL_SALES
    FROM BOOK_SALES
    WHERE DATE_FORMAT(sales_date, '%Y%m') = '202201'
    GROUP BY BOOK_ID
) BS
ON B.BOOK_ID = BS.BOOK_ID
JOIN AUTHOR A
ON B.AUTHOR_ID = A.AUTHOR_ID
GROUP BY B.AUTHOR_ID, B.CATEGORY
ORDER BY B.AUTHOR_ID, B.CATEGORY DESC