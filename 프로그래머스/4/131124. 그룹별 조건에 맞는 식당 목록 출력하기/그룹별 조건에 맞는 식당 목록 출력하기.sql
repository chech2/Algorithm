/*
    1. 리뷰를 제일 많이 작성한 회원의 리뷰
    
    회원 이름, 리뷰 텍스트, 리뷰 작성일
    리뷰 작성일 오름차순, 리뷰 텍스트 오름차순
*/
WITH MEMBER_RANK AS (
    SELECT MEMBER_ID, 
            RANK() OVER(ORDER BY COUNT(*) DESC) AS RANKING
    FROM REST_REVIEW
    GROUP BY MEMBER_ID 
)
SELECT MEMBER_NAME, REVIEW_TEXT, REVIEW_DATE
FROM MEMBER_PROFILE M
JOIN REST_REVIEW R
ON M.MEMBER_ID = R.MEMBER_ID
JOIN MEMBER_RANK MC
ON M.MEMBER_ID = MC.MEMBER_ID
WHERE RANKING = 1
ORDER BY REVIEW_DATE, REVIEW_TEXT