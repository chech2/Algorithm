/*
    조건1. 자동차 종류 '트럭'   
    
    출력: 대여 기록 ID, 대여 금액
    정력: 금액 내림차순, 대여기록 ID 내림차순
*/
SELECT RH.HISTORY_ID AS HISTORY_ID, (DATEDIFF(RH.END_DATE, RH.START_DATE) + 1) * C.DAILY_FEE * (1 - COALESCE(DP.DISCOUNT_RATE, 0) / 100) AS FEE
FROM CAR_RENTAL_COMPANY_CAR C
JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY RH
ON RH.CAR_ID = C.CAR_ID
LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN DP
ON C.CAR_TYPE = DP.CAR_TYPE
AND DP.DURATION_TYPE =
    CASE
        WHEN 90 <= DATEDIFF (RH.END_DATE, RH.START_DATE) THEN '90일 이상'
        WHEN 30 <= DATEDIFF (RH.END_DATE, RH.START_DATE) THEN '30일 이상'
        WHEN 7 <= DATEDIFF (RH.END_DATE, RH.START_DATE) THEN '7일 이상'
        ELSE 0
    END
WHERE C.CAR_TYPE = '트럭'
ORDER BY FEE DESC, RH.HISTORY_ID DESC